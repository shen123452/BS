BEGIN;
SET LOCAL TIME ZONE 'Asia/Shanghai';
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

CREATE TABLE public.knowledge_embedding (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_id BIGINT NOT NULL UNIQUE,
  space_key VARCHAR(128) COLLATE "C" NOT NULL,
  dimension INTEGER NOT NULL,
  embedding public.vector NULL,
  vector_norm DOUBLE PRECISION NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'READY',
  error_code VARCHAR(64) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_embedding_chunk CHECK (chunk_id > 0),
  CONSTRAINT ck_embedding_space CHECK (length(btrim(space_key)) > 0),
  CONSTRAINT ck_embedding_dimension CHECK (dimension BETWEEN 1 AND 16000),
  CONSTRAINT ck_embedding_dims CHECK (embedding IS NULL OR public.vector_dims(embedding) = dimension),
  CONSTRAINT ck_embedding_status CHECK (status IN ('READY','FAILED')),
  CONSTRAINT ck_embedding_norm CHECK (vector_norm IS NULL OR
    (vector_norm > 0 AND vector_norm < 'Infinity'::double precision)),
  CONSTRAINT ck_embedding_nonzero CHECK (embedding IS NULL OR
    (public.vector_norm(embedding) > 0 AND public.vector_norm(embedding) < 'Infinity'::double precision)),
  CONSTRAINT ck_embedding_ready CHECK (status <> 'READY' OR
    (embedding IS NOT NULL AND vector_norm IS NOT NULL AND error_code IS NULL))
);

CREATE INDEX idx_embedding_space_status_chunk
  ON public.knowledge_embedding(space_key, status, chunk_id);

CREATE FUNCTION public.hospital_embedding_set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  -- norm从真实向量计算，不信任应用传来的数值。pgvector类型拒绝NaN/Infinity分量。
  IF NEW.embedding IS NOT NULL THEN
    NEW.vector_norm := public.vector_norm(NEW.embedding);
  ELSE
    NEW.vector_norm := NULL;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_embedding_updated_at
BEFORE INSERT OR UPDATE ON public.knowledge_embedding
FOR EACH ROW EXECUTE FUNCTION public.hospital_embedding_set_updated_at();

COMMENT ON TABLE public.knowledge_embedding IS '知识片段向量，与MySQL通过chunk_id逻辑关联；首版精确检索';
COMMENT ON COLUMN public.knowledge_embedding.chunk_id IS 'MySQL knowledge_chunk.id；没有跨库外键';
COMMENT ON COLUMN public.knowledge_embedding.space_key IS '供应商/模型实现/维度/归一化版本形成的不可混检空间';
COMMENT ON COLUMN public.knowledge_embedding.embedding IS '不固定维度vector，维护重建可更新空间和维度';
COMMENT ON COLUMN public.knowledge_embedding.vector_norm IS '触发器根据真实embedding计算，零范数拒绝';
COMMIT;

